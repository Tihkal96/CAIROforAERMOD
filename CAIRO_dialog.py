class ProcessManager(QObject):
    all_finished = pyqtSignal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self.processes = []  # Will store tuples of (process, fwd_path)
        self.completed_count = 0

    def add_process(self, process, fwd_path):
        self.processes.append((process, fwd_path))
        process.finished.connect(self.on_process_finished)  # Connect to the QProcess object

    def on_process_finished(self, exit_code, exit_status):
        self.completed_count += 1
        if self.completed_count == len(self.processes):
            self.all_finished.emit()


