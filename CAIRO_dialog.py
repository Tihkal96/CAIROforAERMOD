    def create_summary_file(self, project_folder, groups, outdoor_checked, indoor_checked, avg_periods):
        summary_path = os.path.join(project_folder, "RISK", "RISK_SUMMARY.txt")
        with open(summary_path, "w") as f:
            database_path = os.path.join(self.plugin_dir, "database.csv")
            with open(database_path, 'r') as csvfile:
                reader = csv.reader(csvfile, delimiter=';')
                rows = list(reader)
                for row in rows[1:]:
                    if row[1] == self.selected_pollutant:
                        arfc = row[3]
                        iur = row[2]
                        rfc = row[4]
                        break
                else:
                    self.iface.messageBar().pushMessage("Error", "Pollutant not found in database.csv", level=2)
                    return

            receptor_groups = {
                0: [0, 2],  # Adults and Children
                1: [0, 1, 2, 3],  # All
                2: [2],  # Adults
                3: [4]  # Workers
            }
            selected_receptors = receptor_groups[self.receptor_combobox.currentIndex()]

            EC_used = {}
            for risk_type in ["R", "HI", "ACUTE"]:
                EC_list = []
                for receptor in selected_receptors:
                    factors = self.get_exposure_factors(receptor)
                    denominator = factors['BW'] * factors['AT'] * 365 if risk_type == "R" else factors['BW'] * factors[
                        'ED'] * 365
                    EC = (factors['Bo'] * factors['EFgo'] * factors['EF'] * factors[
                        'ED']) / denominator  # Outdoor default
                    EC_list.append(EC)
                if len(selected_receptors) > 1:
                    EC_used[risk_type] = max(EC_list) if self.critical_receptor_checkbox.isChecked() else sum(
                        EC_list) / len(EC_list)
                else:
                    EC_used[risk_type] = EC_list[0]

            C_acc = {}
            if iur != '' and iur != '0':
                C_acc["R"] = 0.000001 / (float(iur) * EC_used["R"]) if float(iur) * EC_used["R"] != 0 else float('inf')
            if rfc != '' and rfc != '0':
                C_acc["HI"] = 1 / (EC_used["HI"] / float(rfc)) if EC_used["HI"] / float(rfc) != 0 else float('inf')
            if arfc != '' and arfc != '0':
                C_acc["ACUTE"] = 1 / (EC_used["ACUTE"] / float(arfc)) if EC_used["ACUTE"] / float(arfc) != 0 else float(
                    'inf')

            selected_receptor = self.receptor_combobox.currentText()
            critical_receptor_state = "true" if self.critical_receptor_checkbox.isChecked() else "false"
            f.write("CAIRO © ~ Air Risk Assessment Module © 2025.\n")
            f.write("Risk Assessment at specific receptors Summary Table\n")
            f.write(f"Receptor: {selected_receptor}; Most Critical Receptor = {critical_receptor_state}\n\n")
            f.write(f"Pollutant: {self.selected_pollutant}\n")
            acc_lines = []
            for risk_type, value in C_acc.items():
                acc_lines.append(f"Acceptable Concentration: C({risk_type}) < {value:.5f}")
            if acc_lines:
                f.write("\n".join(acc_lines) + "\n")
            f.write("\n")

            for group in groups:
                periods = []
                if "1H" in avg_periods[group]:
                    periods.append("1H")
                if "ANNUAL" in avg_periods[group]:
                    periods.append("ANNUAL")
                elif "PERIOD" in avg_periods[group]:
                    periods.append("PERIOD")

                f.write(f"  {group}\n\n")

                site_types = []
                if outdoor_checked:
                    site_types.append(("outdoor", "Outdoor Inhalation Risk"))
                if indoor_checked:
                    site_types.append(("indoor", "Indoor Inhalation Risk"))

                for site_type, site_title in site_types:
                    f.write(f"{site_title}\n")

                    risk_path = os.path.join(project_folder, "RISK", f"risk_{group}", site_type)
                    acute_file = os.path.join(risk_path, "ACUTE",
                                              f"RISK_REC_{'OUT' if site_type == 'outdoor' else 'IND'}_ACUTE_{group}.txt")
                    hi_file = os.path.join(risk_path, "HI",
                                           f"RISK_REC_{'OUT' if site_type == 'outdoor' else 'IND'}_HI_{group}.txt")
                    r_file = os.path.join(risk_path, "R",
                                          f"RISK_REC_{'OUT' if site_type == 'outdoor' else 'IND'}_R_{group}.txt")

                    has_acute = os.path.exists(acute_file)
                    has_hi = os.path.exists(hi_file)
                    has_r = os.path.exists(r_file)
                    chronic_period = avg_periods[group].get("chronic", "PERIOD")

                    data = {}
                    if has_acute:
                        with open(acute_file, "r") as af:
                            lines = af.readlines()[5:]
                            for line in lines:
                                parts = [p.strip() for p in line.split(",")]
                                if len(parts) == 5:
                                    key = (parts[0], parts[1], parts[2])
                                    data[key] = data.get(key, {})
                                    data[key]["ACUTE"] = parts[3]
                                    data[key]["C(1H)"] = parts[4]
                    if has_hi:
                        with open(hi_file, "r") as hf:
                            lines = hf.readlines()[5:]
                            for line in lines:
                                parts = [p.strip() for p in line.split(",")]
                                if len(parts) == 5:
                                    key = (parts[0], parts[1], parts[2])
                                    data[key] = data.get(key, {})
                                    data[key]["HI"] = parts[3]
                                    data[key][f"C({chronic_period})"] = parts[4]
                    if has_r and not has_hi:
                        with open(r_file, "r") as rf:
                            lines = rf.readlines()[5:]
                            for line in lines:
                                parts = [p.strip() for p in line.split(",")]
                                if len(parts) == 5:
                                    key = (parts[0], parts[1], parts[2])
                                    data[key] = data.get(key, {})
                                    data[key]["R"] = parts[3]
                                    data[key][f"C({chronic_period})"] = parts[4]
                    elif has_r:
                        with open(r_file, "r") as rf:
                            lines = rf.readlines()[5:]
                            for line in lines:
                                parts = [p.strip() for p in line.split(",")]
                                if len(parts) == 5:
                                    key = (parts[0], parts[1], parts[2])
                                    data[key] = data.get(key, {})
                                    data[key]["R"] = parts[3]

                    columns = ["Receptor Name", "Easting", "Northing"]
                    if has_acute:
                        columns.extend(["ACUTE", "C(1H)"])
                    if has_hi:
                        columns.append("HI")
                    if has_r:
                        columns.append("R")
                    if has_hi or has_r:
                        columns.append(f"C({chronic_period})")
                    header = ", ".join(f"{col:>20}" for col in columns)
                    f.write(f"  {header}\n")

                    for (name, easting, northing), values in data.items():
                        row = [f"{name:>20}", f"{easting:>20}", f"{northing:>20}"]
                        for col in columns[3:]:
                            value = values.get(col, "N/A")
                            row.append(f"{value:>20}")
                        f.write(f"  {', '.join(row)}\n")
                    f.write("\n")
        with open(summary_path, "r") as f:
            lines = f.readlines()

        cleaned_lines = []
        in_table = False
        header_count = 0
        prev_line_was_header = False

        for line in lines:
            stripped_line = line.strip()
            if stripped_line in ["Outdoor Inhalation Risk", "Indoor Inhalation Risk"]:
                in_table = True
                header_count = 0
                cleaned_lines.append(line)
                continue
            if in_table and "Receptor Name" in stripped_line and "Easting" in stripped_line and "Northing" in stripped_line:
                header_count += 1
                if header_count == 1:
                    cleaned_lines.append(line)
                    prev_line_was_header = True
                continue
            if in_table and not stripped_line:
                in_table = False
                cleaned_lines.append(line)
                continue
            if not prev_line_was_header or header_count > 1:
                cleaned_lines.append(line)
            prev_line_was_header = False

        with open(summary_path, "w") as f:
            f.writelines(cleaned_lines)

        os.startfile(summary_path)

    def get_exposure_factors(self, receptor_idx):
        col = 3 + receptor_idx

        def get_float(row, col, default=0.0):
            item = self.exposure_table.item(row, col)
            return float(item.text()) if item and item.text().strip() else default

        BW = get_float(1, col)  # Row 1: Body Weight
        AT = get_float(2, col)  # Row 2: Averaging Time
        ED = get_float(3, col)  # Row 3: Exposure Duration
        EF = get_float(4, col)  # Row 4: Exposure Frequency
        EFgo = get_float(6, col)  # Row 6: Outdoor Daily Frequency
        Bo = get_float(7, col)  # Row 7: Outdoor Vapor Inhalation Rate
        EFgi = get_float(9, col)  # Row 10: Indoor Daily Frequency
        Bi = get_float(10, col)  # Row 11: Indoor Vapor Inhalation Rate

        return {"BW": BW, "AT": AT, "ED": ED, "EF": EF, "EFgo": EFgo, "Bo": Bo, "EFgi": EFgi, "Bi": Bi}


