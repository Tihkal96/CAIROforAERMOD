    def run_stage(self, stage_index):
        input_folder = QFileDialog.getExistingDirectory(self, "Select Input Folder")
        if input_folder:
            original_dir = os.getcwd()
            try:
                os.chdir(input_folder)
                self.input_folder = input_folder

                executable = os.path.join(self.plugin_dir, f"{self.stage_labels[stage_index].lower()}.exe")

                if not os.path.exists(executable):
                    iface.messageBar().pushMessage(
                        "Error", f"{self.stage_labels[stage_index]}.exe not found in plugin directory.",
                        level=2
                    )
                    return

                loading_movie = QMovie(os.path.join(self.plugin_dir, "loading.gif"))
                self.status_labels[stage_index].setMovie(loading_movie)
                self.status_labels[stage_index].setAlignment(Qt.AlignTop)
                loading_movie.start()

                if self.stage_labels[stage_index] == "AERPLOT":
                    aerplot_folders = [f for f in os.listdir(input_folder) if
                                       os.path.isdir(os.path.join(input_folder, f)) and f.startswith("aerplot")]
                    for aerplot_folder in aerplot_folders:
                        try:
                            folder_path = os.path.join(input_folder, aerplot_folder)
                            os.chdir(folder_path)
                            copied_exe_path = os.path.join(folder_path, "aerplot.exe")
                            shutil.copy(executable, copied_exe_path)
                            time.sleep(5)
                            process = QProcess(self)
                            self.active_processes.append((process, folder_path))
                            process.setProgram(copied_exe_path)
                            process.setProcessChannelMode(QProcess.MergedChannels)
                            process.finished.connect(
                                lambda exit_code, exit_status, idx=stage_index: self.on_process_finished(
                                    exit_code, exit_status, idx))
                            process.start()
                        except Exception as e:
                            print(f"Error launching AERPLOT in {aerplot_folder}: {str(e)}")
                        finally:
                            os.chdir(input_folder)
                else:
                    try:
                        process = QProcess(self)
                        self.active_processes.append((process, None))
                        process.setProgram(executable)
                        process.setProcessChannelMode(QProcess.MergedChannels)
                        process.finished.connect(
                            lambda exit_code, exit_status, idx=stage_index: self.on_process_finished(
                                exit_code, exit_status, idx))
                        process.start()
                    except Exception as e:
                        print(f"Error launching {self.stage_labels[stage_index]}: {str(e)}")
            finally:
                os.chdir(original_dir)

    def on_process_finished(self, exit_code, exit_status, index):
        sender_process = self.sender()
        folder_path = None
        for i, (process, path) in enumerate(self.active_processes[:]):
            if process == sender_process:
                folder_path = path
                self.active_processes.pop(i)
                break

        current_dir = os.getcwd()
        try:
            os.chdir(self.input_folder)

            plugin_dir = os.path.dirname(os.path.realpath(__file__))
            success_icon_path = os.path.join(plugin_dir, "success.png")

            if exit_code == 0:
                pixmap = QPixmap(success_icon_path)
                if pixmap.isNull():
                    self.status_labels[index].setText("✓")
                    self.status_labels[index].setStyleSheet("color: green; font-size: 24px;")
                else:
                    self.status_labels[index].setPixmap(pixmap)
                    self.status_labels[index].setAlignment(Qt.AlignTop)
                    self.status_labels[index].setStyleSheet("")

                if self.stage_labels[index] in ["AERMAP", "AERMOD"]:
                    output_file = f"{self.stage_labels[index].lower()}.out"
                    output_file_path = os.path.join(self.input_folder, output_file)
                    if os.path.exists(output_file_path):
                        QTimer.singleShot(1000, lambda: self.open_output_file(output_file_path))
            else:
                self.status_labels[index].setText("✗")
                self.status_labels[index].setStyleSheet("color: red; font-size: 24px;")

            if self.stage_labels[index] == "AERPLOT" and folder_path:
                exe_path = os.path.join(folder_path, "aerplot.exe")
                if os.path.exists(exe_path):
                    try:
                        os.remove(exe_path)
                    except Exception as e:
                        print(f"Failed to delete aerplot.exe from {exe_path}: {str(e)}")
        finally:
            os.chdir(current_dir)
            if self.status_labels[index].movie():
                self.status_labels[index].movie().stop()
                self.status_labels[index].setMovie(None)

